function applyTexts() {
  document.querySelectorAll('[data-txt]').forEach((element) => {
    const value = TEXTS[element.getAttribute('data-txt')];
    if (value !== undefined) element.textContent = value;
  });

  document.querySelectorAll('[data-alt]').forEach((element) => {
    const value = TEXTS[element.getAttribute('data-alt')];
    if (value !== undefined) element.setAttribute('alt', value);
  });

  document.querySelectorAll('[data-arialabel]').forEach((element) => {
    const value = TEXTS[element.getAttribute('data-arialabel')];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });

  document.querySelectorAll('[data-ttl]').forEach((element) => {
    const value = TEXTS[element.getAttribute('data-ttl')];
    if (value !== undefined) element.setAttribute('title', value);
  });

  document.querySelectorAll('[data-ph]').forEach((element) => {
    const value = TEXTS[element.getAttribute('data-ph')];
    if (value !== undefined) element.setAttribute('placeholder', value);
  });

  const title = TEXTS['page.title'];
  if (title) document.title = title;
}

applyTexts();
